"""RFC 9562 UUID version 7 generator (time-ordered, monotonic within the process).

Layout (128 bits):
    unix_ts_ms (48) | ver=0b0111 (4) | rand_a / counter (12) | var=0b10 (2) | rand_b (62)

`rand_a` is used as a monotonic counter inside the same millisecond (RFC 9562 §6.2,
method 1), so IDs generated by this process are strictly increasing. This keeps B-tree
indexes append-friendly and makes `ORDER BY id` equivalent to creation order.
"""

from __future__ import annotations

import os
import threading
import time
import uuid
from datetime import UTC, datetime

_lock = threading.Lock()
_last_ms = 0
_counter = 0

_MAX_COUNTER = 0xFFF
_RAND_B_MASK = (1 << 62) - 1


def _seed_counter() -> int:
    # Start in the lower half so many IDs fit into one millisecond before rollover.
    return int.from_bytes(os.urandom(2), "big") & 0x7FF


def uuid7() -> uuid.UUID:
    global _last_ms, _counter

    with _lock:
        now_ms = time.time_ns() // 1_000_000
        if now_ms > _last_ms:
            _last_ms = now_ms
            _counter = _seed_counter()
        else:
            # Same millisecond, or the wall clock moved backwards: stay monotonic.
            _counter += 1
            if _counter > _MAX_COUNTER:
                _last_ms += 1
                _counter = _seed_counter()
        ts_ms = _last_ms
        counter = _counter

    rand_b = int.from_bytes(os.urandom(8), "big") & _RAND_B_MASK
    value = (
        ((ts_ms & 0xFFFF_FFFF_FFFF) << 80) | (0x7 << 76) | (counter << 64) | (0b10 << 62) | rand_b
    )
    return uuid.UUID(int=value)


def uuid7_timestamp(value: uuid.UUID) -> datetime:
    """Extract the embedded creation timestamp of a UUIDv7."""
    if value.version != 7:
        raise ValueError("not a UUIDv7")
    return datetime.fromtimestamp((value.int >> 80) / 1000, tz=UTC)
